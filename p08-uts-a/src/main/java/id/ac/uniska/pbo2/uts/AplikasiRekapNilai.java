    private void perbaruiRingkasan() {
        int jumlah = model.getJumlahMahasiswa();
        double rata = model.getRataRataAkhir();
        String rataStr = String.format(java.util.Locale.of("id", "ID"), "%.2f", rata);
        totalLabel.setText("Jumlah mahasiswa: " + jumlah + ", rata-rata nilai akhir: " + rataStr);
    }

    private void tampilkanError(String pesan, javax.swing.JTextField field) {
        statusLabel.setForeground(java.awt.Color.RED);
        statusLabel.setText(pesan);
        field.requestFocus();
    }
    
