    private void simpanButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_simpanButtonActionPerformed
        statusLabel.setText("");
    
        String npm = npmField.getText().trim();
        String nama = namaField.getText().trim();
        String tugasStr = tugasField.getText().trim();
        String utsStr = utsField.getText().trim();
        String uasStr = uasField.getText().trim();

    // Validasi 1: NPM harus 10 digit angka
    if (!npm.matches("\\d{10}")) {
        tampilkanError("NPM harus 10 digit angka", npmField);
        return;
    }

    // Validasi 2: NPM tidak boleh ganda
    if (model.isNpmAda(npm)) {
        tampilkanError("NPM " + npm + " sudah terdaftar", npmField);
        return;
    }

    // Validasi 3: Nama wajib diisi
    if (nama.isEmpty()) {
        tampilkanError("Nama wajib diisi", namaField);
        return;
    }

    try {
        int tugas = Integer.parseInt(tugasStr);
        if (tugas < 0 || tugas > 100) {
            tampilkanError("Nilai Tugas harus angka bulat 0 sampai 100", tugasField);
            return;
        }

        int uts = Integer.parseInt(utsStr);
        if (uts < 0 || uts > 100) {
            tampilkanError("Nilai UTS harus angka bulat 0 sampai 100", utsField);
            return;
        }

        int uas = Integer.parseInt(uasStr);
        if (uas < 0 || uas > 100) {
            tampilkanError("Nilai UAS harus angka bulat 0 sampai 100", uasField);
            return;
        }

        // Masukkan data jika lolos validasi
        NilaiMahasiswa mhs = new NilaiMahasiswa(npm, nama, tugas, uts, uas);
        model.tambahData(mhs);
        
        // Perbarui ringkasan otomatis
        perbaruiRingkasan();
        
        // Bersihkan form setelah sukses
        npmField.setText("");
        namaField.setText("");
        tugasField.setText("");
        utsField.setText("");
        uasField.setText("");
        statusLabel.setText("");
        npmField.requestFocus();

    } catch (NumberFormatException e) {
        if (!tugasStr.matches("\\d+")) {
            tampilkanError("Nilai Tugas harus angka bulat 0 sampai 100", tugasField);
        } else if (!utsStr.matches("\\d+")) {
            tampilkanError("Nilai UTS harus angka bulat 0 sampai 100", utsField);
        } else {
            tampilkanError("Nilai UAS harus angka bulat 0 sampai 100", uasField);
        }
    }

    }//GEN-LAST:event_simpanButtonActionPerformed

