    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed
        java.util.List<javax.swing.JComponent> salah = new java.util.ArrayList<>();

        // Memanggil Validator untuk memeriksa setiap isian
        if (!tandai(npmField, npmPesanLabel, Validator.npm(npmField.getText()))) salah.add(npmField);
        if (!tandai(namaLengkapField, namaPesanLabel, Validator.nama(namaLengkapField.getText()))) salah.add(namaLengkapField);

        // Asumsi index 0 adalah "Pilih program studi"
        if (!tandai(prodiCombo, prodiPesanLabel, prodiCombo.getSelectedIndex() == 0 ? "Pilih salah satu program studi" : null)) salah.add(prodiCombo);
        if (!tandai(emailField, emailPesanLabel, Validator.email(emailField.getText()))) salah.add(emailField);
        if (!tandai(nomorHPField, nomorPesanLabel, Validator.nomorHp(nomorHPField.getText()))) salah.add(nomorHPField);

        if (!salah.isEmpty()) {
            statusLabel.setText(salah.size() + " isian perlu diperbaiki");
            salah.get(0).requestFocusInWindow();
        return; 
    }
        // Jika tidak ada error, kosongkan label sebelum lanjut menampilkan JOptionPane
        statusLabel.setText("");

        // Mengambil data dari form
        String nama = namaLengkapField.getText();
        String npm = npmField.getText();
        String prodi = prodiCombo.getSelectedItem().toString();

        String jenisAnggota = "";
        if (mahasiswaRadioButton.isSelected()) {
            jenisAnggota = "Mahasiswa";
        } else if (dosenRadioButton.isSelected()) {
            jenisAnggota = "Dosen";
        } else if (umumRadioButton.isSelected()) {
            jenisAnggota = "Umum";
        }

        String email = emailField.getText();
        String nomorHP = nomorHPField.getText();
        String alamat = alamatArea.getText();
        String ringkasan = "=== RINGKASAN PENDAFTARAN ANGGOTA ===\n"
        + "Nama Lengkap : " + nama + "\n"
        + "NPM : " + npm + "\n"
        + "Program Studi : " + prodi + "\n"
        + "Jenis Anggota : " + jenisAnggota + "\n"
        + "Email : " + email + "\n"
        + "Nomor HP : " + nomorHP + "\n"
        + "Alamat : " + alamat;
        javax.swing.JOptionPane.showMessageDialog(this, ringkasan, "Data Pendaftaran", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_daftarButtonActionPerformed

    private void batalButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_batalButtonActionPerformed
        // Cek apakah ada isian yang tidak kosong
        if (!npmField.getText().isBlank() || !namaLengkapField.getText().isBlank() ||
            !emailField.getText().isBlank() || !nomorHPField.getText().isBlank() ||
            !alamatArea.getText().isBlank()) {

            int jawab = javax.swing.JOptionPane.showConfirmDialog(this,
                "Data yang sudah diisi akan dihapus. Lanjutkan?", "Konfirmasi",
                javax.swing.JOptionPane.YES_NO_OPTION, javax.swing.JOptionPane.WARNING_MESSAGE);

            if (jawab != javax.swing.JOptionPane.YES_OPTION) {
                return; // Hentikan proses batal jika pengguna memilih 'No'
            }
        }

        // Jika form kosong atau pengguna pilih 'Yes', jalankan pengosongan
        namaLengkapField.setText("");
        npmField.setText("");
        emailField.setText("");
        nomorHPField.setText("");
        alamatArea.setText("");
        prodiCombo.setSelectedIndex(0);
        mahasiswaRadioButton.setSelected(true);
        persetujuanCheckBox.setSelected(false);
        daftarButton.setEnabled(false);

        // Hilangkan tanda error merah jika ada
        tandai(npmField, npmPesanLabel, null);
        tandai(namaLengkapField, namaPesanLabel, null);
        tandai(prodiCombo, prodiPesanLabel, null);
        tandai(emailField, emailPesanLabel, null);
        tandai(nomorHPField, nomorPesanLabel, null);

        statusLabel.setText("");
        npmField.requestFocus();
    }//GEN-LAST:event_batalButtonActionPerformed

