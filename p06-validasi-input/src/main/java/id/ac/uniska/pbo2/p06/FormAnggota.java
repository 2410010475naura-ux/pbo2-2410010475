    // METHOD BANTU
    private boolean periksaNpm() {
        return tandai(npmField, npmPesanLabel, Validator.npm(npmField.getText()));
    }

    private boolean periksaNama() {
        return tandai(namaLengkapField, namaPesanLabel, Validator.nama(namaLengkapField.getText()));
    }

    private boolean periksaProdi() {
        String kesalahan = null;
        if (prodiCombo.getSelectedIndex() == 0) {
            kesalahan = "Pilih salah satu program studi";
        }
        return tandai(prodiCombo, prodiPesanLabel, kesalahan);
    }

    private boolean periksaEmail() {
        return tandai(emailField, emailPesanLabel, Validator.email(emailField.getText()));
    }

    private boolean periksaHp() {
        return tandai(nomorHPField, nomorPesanLabel, Validator.nomorHp(nomorHPField.getText()));
    }

    private boolean tandai(javax.swing.JComponent isian, javax.swing.JLabel pesan, String kesalahan) {
        isian.putClientProperty("JComponent.outline", (kesalahan == null) ? null : "error");
        pesan.setText((kesalahan == null) ? " " : kesalahan);
        if (kesalahan != null) {
            pesan.setForeground(warnaKesalahan());
        }
        return kesalahan == null;
    }   
    
    static java.awt.Color warnaKesalahan() {
        return com.formdev.flatlaf.FlatLaf.isLafDark() ? new java.awt.Color(0xFF8A80) : new java.awt.Color(0xC62828);
    }
    
    private void batalButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_batalButtonActionPerformed
        // Cek apakah ada isian yang tidak kosong
        if (!npmField.getText().isBlank() || !namaLengkapField.getText().isBlank() ||
            !emailField.getText().isBlank() || !nomorHPField.getText().isBlank() ||
            !alamatArea.getText().isBlank()) {

            int jawab = javax.swing.JOptionPane.showConfirmDialog(this,
                "Data yang sudah diisi akan dihapus. Lanjutkan?", "Konfirmasi",
                javax.swing.JOptionPane.YES_NO_OPTION, javax.swing.JOptionPane.WARNING_MESSAGE);

            if (jawab != javax.swing.JOptionPane.YES_OPTION) {
                return; // Hentikan proses batal jika pengguna memilih 'No'
            }
        }

        // Jika form kosong atau pengguna pilih 'Yes', jalankan pengosongan
        namaLengkapField.setText("");
        npmField.setText("");
        emailField.setText("");
        nomorHPField.setText("");
        alamatArea.setText("");
        prodiCombo.setSelectedIndex(0);
        mahasiswaRadio.setSelected(true);
        persetujuanCheckBox.setSelected(false);
        daftarButton.setEnabled(false);

        // Hilangkan tanda error merah jika ada
        tandai(npmField, npmPesanLabel, null);
        tandai(namaLengkapField, namaPesanLabel, null);
        tandai(prodiCombo, prodiPesanLabel, null);
        tandai(emailField, emailPesanLabel, null);
        tandai(nomorHPField, nomorPesanLabel, null);

        statusLabel.setText("");
        npmField.requestFocus();
    }//GEN-LAST:event_batalButtonActionPerformed

    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed
        java.util.List<javax.swing.JComponent> salah = new java.util.ArrayList<>();

        // Memeriksa semua isian form
        if (!periksaNpm()) salah.add(npmField);
        if (!periksaNama()) salah.add(namaLengkapField);
        if (!periksaProdi()) salah.add(prodiCombo);
        if (!periksaEmail()) salah.add(emailField);
        if (!periksaHp()) salah.add(nomorHPField);

        // Jika ada isian yang salah
        if (!salah.isEmpty()) {
            statusLabel.setText(salah.size() + " isian perlu diperbaiki");
            salah.get(0).requestFocusInWindow(); // Arahkan fokus ke kesalahan pertama
            return; 
        }

        // Jika semua isian valid
        statusLabel.setText("");

        String jenisAnggota = "Mahasiswa";
        if (dosenRadio.isSelected()) {
            jenisAnggota = "Dosen";
        } else if (umumRadio.isSelected()) {
            jenisAnggota = "Umum";
        }

        String pesan = "Pendaftaran berhasil.\n\n"
            + "NPM: " + npmField.getText() + "\n"
            + "Nama: " + namaLengkapField.getText().trim() + "\n"
            + "Jenis anggota: " + jenisAnggota;

        javax.swing.JOptionPane.showMessageDialog(this, pesan, "Pendaftaran Berhasil", javax.swing.JOptionPane.INFORMATION_MESSAGE);   
    }//GEN-LAST:event_daftarButtonActionPerformed

